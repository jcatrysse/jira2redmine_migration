<?php

declare(strict_types=1);

namespace Jira2Redmine\Workflows;

/**
 * Jira's post function "assign to the current user" as a redmine_custom_workflows script (Jan, decision 13):
 * one per tracker and target status, for the projects whose Jira workflow has it. Redmine has no post
 * functions; the plugin runs the script before an issue is saved (v2.1.2 on 5.1, the 7.0 branch on 7.0).
 */
final class WorkflowScripts
{
    /** Name prefix of the custom workflows the runner owns: it creates, updates and removes only these. */
    public const NAME_PREFIX = 'j2r: ';

    public static function name(int $tracker, int $status): string
    {
        return sprintf('%sassign to the current user, tracker #%d, to status #%d', self::NAME_PREFIX, $tracker, $status);
    }

    /**
     * @param list<int> $oldStatuses the statuses the transition starts from, 0 for the creation of an issue
     * @param list<string> $transitions the Jira transition names, for the comment
     */
    public static function assignToCurrentUser(int $tracker, int $status, array $oldStatuses, array $transitions): string
    {
        $old = array_values(array_unique(array_map('intval', $oldStatuses)));
        sort($old);

        return implode("\n", [
            sprintf(
                '# Jira post function "assign to the current user" (%s), generated by tools/workflow_proposal.php',
                implode(', ', $transitions)
            ),
            sprintf('if tracker_id == %d && status_id == %d && (new_record? || status_id_changed?) &&', $tracker, $status),
            sprintf('   [%s].include?(new_record? ? 0 : status_id_was.to_i) &&', implode(', ', $old)),
            '   User.current.logged? && assignable_users.include?(User.current)',
            '  self.assigned_to = User.current',
            'end',
        ]);
    }
}
